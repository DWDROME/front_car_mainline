#pragma once

#include "types.hpp"

//----------------------------------------------------------------------------------------------------------------------
//  @brief      初始化电机输出和反馈读取
//  @param      enabled  1 允许后续下发 PWM / 0 只清零 PWM 和编码器
//  @return     int      1 驱动输出已允许 / 0 驱动输出保持禁止
//  @note       会初始化 IMU yaw-rate 反馈。enabled=0 时仍可读到零速反馈，但 drive_output_apply() 不会驱动电机。
//----------------------------------------------------------------------------------------------------------------------
int drive_output_init(int enabled);

//----------------------------------------------------------------------------------------------------------------------
//  @brief      立即关闭左右电机 PWM
//  @note       只写 PWM 为 0，不改变 g_drive_enabled；下次 apply 是否能驱动仍由 init 的 enabled 决定。
//----------------------------------------------------------------------------------------------------------------------
void drive_output_stop();

//----------------------------------------------------------------------------------------------------------------------
//  @brief      读取一个控制周期内的编码器和 IMU 反馈
//  @param      fb         输出反馈；left/right_speed_count 是本周期编码器增量
//  @param      period_ms  调用方期望控制周期，实测周期异常时使用它
//  @note       当前硬件映射：QUAD1=left，QUAD2=right；编码器方向在本函数内修正。
//----------------------------------------------------------------------------------------------------------------------
void drive_output_read_feedback(control_feedback_t *fb, int period_ms);

//----------------------------------------------------------------------------------------------------------------------
//  @brief      按控制输出下发左右 PWM
//  @param      ctrl  solve_control_input_with_feedback() 计算出的控制结果
//  @note       未使能、停车请求或 input_valid=0 时会保持停止。
//              当前硬件映射：left -> PWM2，right -> PWM1；不要在控制层重复修正。
//----------------------------------------------------------------------------------------------------------------------
void drive_output_apply(const control_state_t *ctrl);
