#pragma once

#include "types.hpp"

//----------------------------------------------------------------------------------------------------------------------
//  @brief      环岛状态机入口
//  @param      rt  运行时状态；读取单侧 L、直线判断、编码器累计值，更新 rt->ring 和检测用边界
//  @note       kind 表示左/右环；state 按 BEGIN -> IN -> RUN -> OUT -> END 推进。
//              ring 内部边界补线/截线只服务检测和状态连续，不发布当前帧控制中线。
//              cross 已活动时不进入新环岛，元素互斥顺序由 element_process() 统一控制。
//----------------------------------------------------------------------------------------------------------------------
void ring_process(runtime_t *rt);

//----------------------------------------------------------------------------------------------------------------------
//  @brief      判断当前环岛阶段是否禁止新十字入口
//  @param      rt  运行时状态
//  @return     int  1 禁止新十字入口 / 0 允许十字入口按自身条件判断
//  @note       对齐参考版 cross entry 的 ring_times < 2：pending second、false-ring wait 和已确认环岛都挡新十字。
//----------------------------------------------------------------------------------------------------------------------
int ring_blocks_cross_entry(const runtime_t *rt);
