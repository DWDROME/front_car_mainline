#pragma once

#include <opencv2/core.hpp>

#include "types.hpp"

//----------------------------------------------------------------------------------------------------------------------
//  @brief      清空巡线运行时状态
//  @param      rt  运行时状态
//  @note       会恢复默认控制中心和中线起点；不会读取图像，也不会输出电机控制。
//----------------------------------------------------------------------------------------------------------------------
void tracking_reset(runtime_t *rt);

//----------------------------------------------------------------------------------------------------------------------
//  @brief      执行当前帧主巡线流程
//  @param      rt   运行时状态；输入图像必须已写入 rt->gray，且 gray_valid 为 1
//  @return     int  1 本帧得到可用控制中线 / 0 seed、trace、中线或预瞄失败
//  @note       主链顺序：seed/trace -> boundary+rptsc candidates -> element state -> selected midline -> guide_error。
//              本函数只生成视觉控制结果，不直接输出电机 duty。
//----------------------------------------------------------------------------------------------------------------------
int tracking_process_frame(runtime_t *rt);

//----------------------------------------------------------------------------------------------------------------------
//  @brief      判断当前帧是否有可用于控制的中线
//  @param      rt   运行时状态
//  @return     int  1 track_type/reject_reason/mid.step 均有效 / 0 不可用于控制
//  @note       这里只读 track 结果，不重新计算图像。
//----------------------------------------------------------------------------------------------------------------------
int track_line_found(const runtime_t *rt);
